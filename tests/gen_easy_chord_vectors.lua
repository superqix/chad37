-- Generates tests/easy_chord_vectors.inc by driving Chordcade's real engine, so the C port is
-- checked against Chordcade rather than against itself. Run from a Chordcade checkout:
--   cd ~/GitHub/chorg && lua ~/GitHub/chordpad37/tests/gen_easy_chord_vectors.lua > ~/GitHub/chordpad37/tests/easy_chord_vectors.inc

-- The engine only needs the Solar2D globals it touches at load time and while scheduling.
_G.system = {
    getTimer = function() return 0 end,
    pathForFile = function() return nil end,
    getInfo = function() return "" end,
    DocumentsDirectory = "docs",
    ResourceDirectory = "res",
    activate = function() end,
}
_G.timer = {
    performWithDelay = function() return {} end,
    cancel = function() end,
    pause = function() end,
    resume = function() end,
}
_G.native = { getProperty = function() return nil end }
_G.Runtime = {
    addEventListener = function() end,
    removeEventListener = function() end,
    dispatchEvent = function() end,
}

local chordEngine = require("module.engine.chordEngine")
local state = require("module.engine.state")

local LOW_KEY, HIGH_KEY = 48, 84 -- the SMK-37's 37 keys at octave 0

-- Runs one held-key set through the engine and returns its chords, highest root first.
local function run(held)
    state.set("isEasyMode", true)
    -- Chordcade transposes chords up by default to suit its small on-screen keyboard. Physical
    -- keys sound where they are played.
    state.set("isChordOctaveActive", false)
    local heldKeys = {}
    for _, note in ipairs(held) do heldKeys[note] = { velocity = 100 } end
    state.set("heldKeys", heldKeys)
    chordEngine.recomputeKeyboardChords()

    local chords = {}
    for root, chord in pairs(state.get("activeChords") or {}) do
        chords[#chords + 1] = { root = root, suffix = chord.chordSuffix, tones = chord.chordNotes }
    end
    table.sort(chords, function(a, b) return a.root > b.root end)

    state.set("heldKeys", {})
    chordEngine.recomputeKeyboardChords()
    return chords
end

local seen = {}

local function emit(held)
    local key = table.concat(held, ",")
    if seen[key] then return end
    seen[key] = true
    local chords = run(held)
    local parts = {}
    for _, chord in ipairs(chords) do
        parts[#parts + 1] = string.format('{%d,"%s",%d,{%s}}', chord.root, chord.suffix,
            #chord.tones, table.concat(chord.tones, ","))
    end
    print(string.format("{%d,{%s},%d,{%s}},", #held, table.concat(held, ","), #chords,
        table.concat(parts, ",")))
end

local coreMIDI = require("module.engine.coreMIDI")

print("/* Generated by tests/gen_easy_chord_vectors.lua. Do not edit. */")

-- Every modifier combination on every root, keeping only modifiers on the keyboard.
for root = LOW_KEY, HIGH_KEY do
    local modifiers = { coreMIDI.getPrecedingModifierKeys(root) }
    for mask = 0, 15 do
        local held = { root }
        for bit = 0, 3 do
            local modifier = modifiers[bit + 1]
            if mask & (1 << bit) ~= 0 and modifier and modifier >= LOW_KEY then
                held[#held + 1] = modifier
            end
        end
        emit(held)
    end
end

-- Fixed pseudo-random hands, so regenerating gives the same file on any Lua.
local seed = 12345
local function nextValue(limit)
    seed = (seed * 1103515245 + 12345) % 2147483648
    return (seed >> 16) % limit
end

for _ = 1, 400 do
    local chosen, held = {}, {}
    for _ = 1, 2 + nextValue(9) do
        local note = LOW_KEY + nextValue(HIGH_KEY - LOW_KEY + 1)
        if not chosen[note] then
            chosen[note] = true
            held[#held + 1] = note
        end
    end
    table.sort(held)
    emit(held)
end
