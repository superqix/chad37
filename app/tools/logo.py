"""Turn a pixel-art text file (app/logo/*.txt) into a C header for the boot screen.

  logo.py ART.txt --out HEADER.h [--name chad_logo]

The art file: '#' comment lines, then the palette (one "KEY = RRGGBB" line per colour, KEY a single character), the
line "end", then the rows, one character per pixel ('.' is the background). The header holds NAME_W and NAME_H (in
pixels), NAME_pal (RGB565, the LCD's format) and NAME_runs: {y, x, n, colour} for each horizontal run of one colour,
which the app draws with lcd_fill. fm1.toml runs it before every build (gen).
"""
import argparse
import sys


def load(path):
    pal, rows, body = {}, [], False
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        line = line.rstrip("\r\n")
        if not body:
            if line.startswith("#") or not line.strip():
                continue
            if line.strip() == "end":
                body = True
                continue
            key, _, val = (t.strip() for t in line.partition("="))
            if len(key) != 1 or key == "." or len(val) != 6:
                sys.exit(f"{path}:{n}: expected KEY = RRGGBB, got {line!r}")
            pal[key] = int(val, 16)
        elif line.strip():
            bad = set(line) - set(pal) - {"."}
            if bad:
                sys.exit(f"{path}:{n}: colours not in the palette: {''.join(sorted(bad))}")
            rows.append(line)
    if not rows:
        sys.exit(f"{path}: no rows after 'end'")
    return pal, rows


def rgb565(v):
    r, g, b = v >> 16, (v >> 8) & 0xFF, v & 0xFF
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("art")
    ap.add_argument("--out", required=True)
    ap.add_argument("--name", default="chad_logo")
    a = ap.parse_args()
    pal, rows = load(a.art)
    keys = sorted(pal)
    idx = {k: i for i, k in enumerate(keys)}
    w, h = max(map(len, rows)), len(rows)
    if w > 255 or h > 255 or len(keys) > 255:
        sys.exit(f"{a.art}: {w}x{h} with {len(keys)} colours does not fit the header's bytes")
    runs = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch, n = row[x], 1
            while x + n < len(row) and row[x + n] == ch:
                n += 1
            if ch != ".":
                runs.append((y, x, n, idx[ch]))
            x += n
    N = a.name
    out = [f"/* generated by app/tools/logo.py from {a.art}: do not edit */",
           "#pragma once",
           "#include <stdint.h>",
           f"#define {N.upper()}_W {w}u",
           f"#define {N.upper()}_H {h}u",
           f"#define {N.upper()}_NRUNS {len(runs)}u",
           f"static const uint16_t {N}_pal[{len(keys)}] = {{" + ", ".join(f"0x{rgb565(pal[k]):04X}" for k in keys) + "};",
           f"static const uint8_t {N}_runs[{len(runs)}][4] = {{"]
    for i in range(0, len(runs), 8):
        out.append("    " + " ".join("{%d,%d,%d,%d}," % r for r in runs[i:i + 8]))
    out.append("};")
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
